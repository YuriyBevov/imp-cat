  assert.match(html, /id="editor-font-size"/)
  assert.match(html, /data-editor-action="insert-tab"/)
  assert.match(app, /runSelectedEditorAction\("font-size"/)
  assert.match(app, /insertEditorTab/)
  assert.doesNotMatch(app, /const formattingActions =/)
  assert.match(app, /document\.execCommand\(action, false\)/)
  assert.match(app, /"align-left": "left"/)
  assert.match(app, /"align-center": "center"/)
  assert.match(app, /"align-right": "right"/)
  assert.match(app, /изменение жирности текста/)
  assert.match(app, /изменение курсива текста/)
  assert.match(app, /Перемещенные внутрь блока сегменты не будут учавствовать в сборке финального документа/)
  assert.doesNotMatch(styles, /↘ изменить размер/)
  assert.match(app, /Вернуть в исходное положение в документе/)
  assert.doesNotMatch(app, /"restore-page"|"previous-page"|"next-page"/)
