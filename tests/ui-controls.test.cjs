  assert.match(styles, /#docx-host section\.docx/)
  assert.match(styles, /var\(--grid-size\)/)
  assert.match(html, /id="fit-width"/)
  assert.match(html, /id="upload-button"/)
  assert.match(html, /id="resolve-overlaps"/)
  assert.match(html, /src="\/history-model\.js"/)
  assert.match(html, /src="\/segmentation-model\.js"/)
  assert.match(html, /id="view-scale" type="range" min="25" max="250"/)
  assert.match(app, /setViewScale\(Number\(elements\.viewScale\.value\)\)/)
  assert.match(app, /fitDocumentWidth/)
  assert.match(app, /resolveSegmentOverlaps/)
  assert.match(app, /getSegmentHorizontalGeometry/)
  assert.match(app, /getPhysicalPageSize/)
  assert.match(app, /getFlowPageCount/)
  assert.match(app, /getFlowPagePlacement/)
  assert.match(app, /layoutSequentialFlowBoxes/)
  assert.match(app, /icat-flow-page/)
  assert.match(app, /isCandidateInNormalFlow/)
  assert.doesNotMatch(app, /scrollHeight.*slice|icat-derived-page|getPageSlice/)
  assert.match(app, /renderPageInsertControls/)
  assert.match(app, /insertBlankPage/)
  assert.match(app, /removeEmptyPage/)
  assert.match(app, /undoRemovedPage/)
  assert.match(app, /ICATLayout\.isPageEmpty/)
  assert.match(app, /remapPageIndexAfterRemoval/)
  assert.match(app, /undoInsertedPage/)
  assert.match(app, /commitHistory\(before, "добавление страницы"/)
  assert.match(app, /createParkingArea/)
  assert.match(app, /createEditorLayout/)
  assert.match(app, /setParkingSurfaceWidth/)
  assert.match(app, /observeParkingResize/)
  assert.match(app, /new ResizeObserver/)
  assert.match(app, /measureDropSurfaces/)
  assert.match(app, /findDropSurface/)
  assert.match(app, /requestAnimationFrame\(flushMove\)/)
  assert.match(app, /window\.addEventListener\("pointermove", move\)/)
  const dropLookup = app.match(/function findDropSurface[\s\S]*?\n}/)?.[0] || ''
  assert.doesNotMatch(dropLookup, /getBoundingClientRect/)
  assert.match(app, /ICATLayout\.isDocumentSegment/)
  assert.match(app, /segment\.pageIndex = null/)
  assert.match(app, /state\.parkingOverlay\.style\.height/)
  assert.match(styles, /\.icat-editor-layout[\s\S]*grid-template-columns: max-content max-content/)
  assert.match(styles, /\.icat-parking[\s\S]*position: sticky/)
  assert.match(styles, /\.icat-parking[\s\S]*resize: both/)
  assert.match(styles, /\[hidden\][\s\S]*display: none !important/)
  assert.match(html, /буфер справа от листов/)
  assert.match(app, /!sourceElement\.closest\("td, th"\)/)
  assert.match(app, /const pages = state\.pages\.map/)
  assert.match(app, /pageIndex: segment\.pageIndex/)
  assert.match(app, /screenDeltaToDocument/)
  assert.match(app, /captureZoomAnchor/)
  assert.match(app, /getZoomScrollAdjustment/)
  assert.match(app, /event\.ctrlKey \|\| event\.metaKey/)
  assert.match(app, /handleWorkspaceZoom/)
  assert.match(app, /beginMarqueeSelection/)
  assert.match(app, /ICATSegmentation\.collectTextCandidates/)
  assert.match(app, /hideCandidateSource\(candidate\)/)
  assert.match(app, /selectedIds: new Set\(\)/)
  assert.match(app, /getSegmentActionTargets/)
  assert.match(app, /runEditorAction/)
